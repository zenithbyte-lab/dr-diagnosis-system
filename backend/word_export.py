"""Generate Word diagnosis report using python-docx."""
import os
from datetime import datetime
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT
from .config import REPORT_DIR


RISK_COLORS = {
    "Low": RGBColor(0x10, 0xB9, 0x81),
    "Low-Medium": RGBColor(0x3B, 0x82, 0xF6),
    "Medium": RGBColor(0xF5, 0x9E, 0x0B),
    "High": RGBColor(0xEF, 0x44, 0x44),
    "Critical": RGBColor(0xDC, 0x26, 0x26),
}


def generate_report(diagnosis) -> str:
    doc = Document()

    # --- Title ---
    title = doc.add_heading("Diabetic Retinopathy Diagnosis Report", level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER

    doc.add_paragraph(f"Report ID: {diagnosis.uid}").alignment = WD_ALIGN_PARAGRAPH.CENTER
    doc.add_paragraph(f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}").alignment = WD_ALIGN_PARAGRAPH.CENTER
    doc.add_paragraph("")

    # --- Patient Information ---
    doc.add_heading("1. Patient Information", level=1)
    table = doc.add_table(rows=4, cols=2)
    table.style = "Light Grid Accent 1"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    fields = [
        ("Patient Name", diagnosis.patient_name or "N/A"),
        ("Age", str(diagnosis.patient_age) if diagnosis.patient_age else "N/A"),
        ("Gender", (diagnosis.patient_gender or "N/A").capitalize()),
        ("Eye Side", (diagnosis.eye_side or "unknown").capitalize()),
    ]
    for i, (label, value) in enumerate(fields):
        table.rows[i].cells[0].text = label
        table.rows[i].cells[1].text = value

    doc.add_paragraph("")

    # --- Original Fundus Image ---
    doc.add_heading("2. Fundus Image", level=1)
    try:
        doc.add_picture(diagnosis.original_image, width=Inches(3.5))
        doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    except (FileNotFoundError, OSError):
        doc.add_paragraph("[Image not available]")

    # --- Grad-CAM Heatmap ---
    doc.add_heading("3. Grad-CAM Attention Heatmap", level=1)
    doc.add_paragraph(
        "The heatmap below highlights regions the model focused on when making this diagnosis. "
        "Warm colors (red/yellow) indicate high attention areas."
    )
    try:
        doc.add_picture(diagnosis.heatmap_image, width=Inches(3.5))
        doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    except (FileNotFoundError, OSError):
        doc.add_paragraph("[Heatmap not available]")

    # --- Diagnosis Result ---
    doc.add_heading("4. Diagnosis Result", level=1)
    result_table = doc.add_table(rows=3, cols=2)
    result_table.style = "Light Grid Accent 1"
    result_table.alignment = WD_TABLE_ALIGNMENT.CENTER

    result_table.rows[0].cells[0].text = "Severity Level"
    run = result_table.rows[0].cells[1].paragraphs[0].add_run(diagnosis.pred_label)
    run.bold = True
    color = RISK_COLORS.get(diagnosis.risk_level, RGBColor(0, 0, 0))
    run.font.color.rgb = color

    result_table.rows[1].cells[0].text = "Confidence"
    result_table.rows[1].cells[1].text = f"{diagnosis.confidence}%"

    result_table.rows[2].cells[0].text = "Risk Level"
    run2 = result_table.rows[2].cells[1].paragraphs[0].add_run(diagnosis.risk_level)
    run2.bold = True
    run2.font.color.rgb = color

    doc.add_paragraph("")

    # --- Class Probabilities ---
    doc.add_heading("5. Classification Probabilities", level=1)
    prob_table = doc.add_table(rows=6, cols=2)
    prob_table.style = "Light Grid Accent 1"
    prob_table.alignment = WD_TABLE_ALIGNMENT.CENTER
    prob_table.rows[0].cells[0].text = "Class"
    prob_table.rows[0].cells[1].text = "Probability"
    probs = [
        ("No DR (Level 0)", diagnosis.prob_no_dr),
        ("Mild (Level 1)", diagnosis.prob_mild),
        ("Moderate (Level 2)", diagnosis.prob_moderate),
        ("Severe (Level 3)", diagnosis.prob_severe),
        ("Proliferative (Level 4)", diagnosis.prob_proliferative),
    ]
    for i, (label, prob) in enumerate(probs):
        prob_table.rows[i + 1].cells[0].text = label
        prob_table.rows[i + 1].cells[1].text = f"{prob}%"

    doc.add_paragraph("")

    # --- Recommendation ---
    doc.add_heading("6. Clinical Recommendation", level=1)
    doc.add_paragraph(diagnosis.recommendation or "N/A")

    # --- Disclaimer ---
    doc.add_paragraph("")
    disclaimer = doc.add_paragraph()
    run = disclaimer.add_run(
        "Disclaimer: This report is generated by an AI-assisted diagnosis system for reference only. "
        "It does not constitute a formal medical diagnosis. Please consult a qualified ophthalmologist "
        "for clinical decision-making."
    )
    run.font.size = Pt(8)
    run.font.color.rgb = RGBColor(0x99, 0x99, 0x99)

    # Save
    path = os.path.join(REPORT_DIR, f"{diagnosis.uid}_report.docx")
    doc.save(path)
    return path
